import { execFileSync } from "node:child_process";
import {
  mkdirSync,
  readdirSync,
  renameSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const issuesDirectory = join(projectRoot, ".issues");
const fields = [
  "number",
  "title",
  "body",
  "state",
  "url",
  "labels",
  "assignees",
  "milestone",
  "createdAt",
  "updatedAt",
].join(",");

function readArgument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? undefined : process.argv[index + 1];
}

function runGh(arguments_) {
  return execFileSync("gh", arguments_, {
    cwd: projectRoot,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "inherit"],
  }).trim();
}

function quote(value) {
  return JSON.stringify(value);
}

function issueFilename(number) {
  return `iss-${String(number).padStart(4, "0")}.md`;
}

function markdownCell(value) {
  return String(value).replaceAll("|", "\\|").replaceAll("\n", " ");
}

function writeAtomically(path, contents) {
  const temporaryPath = `${path}.tmp-${process.pid}`;
  writeFileSync(temporaryPath, contents, "utf8");
  renameSync(temporaryPath, path);
}

function renderIssue(issue) {
  const labels = issue.labels.map((label) => label.name);
  const assignees = issue.assignees.map((assignee) => assignee.login);
  const milestone = issue.milestone?.title ?? null;
  const heading = `ISS-${String(issue.number).padStart(4, "0")}`;
  const body = issue.body.trimEnd();

  return `---
id: ${issue.number}
title: ${quote(issue.title)}
status: ${issue.state.toLowerCase()}
source: github
github_url: ${quote(issue.url)}
labels: ${quote(labels)}
assignees: ${quote(assignees)}
milestone: ${milestone === null ? "null" : quote(milestone)}
created_at: ${quote(issue.createdAt)}
updated_at: ${quote(issue.updatedAt)}
---

<!-- Generated by scripts/sync-github-issues.mjs. Edit the GitHub issue, then run pnpm issues:pull. -->

# ${heading} — ${issue.title}

GitHub: [#${issue.number}](${issue.url})

${body}
`;
}

function renderIndex(repository, issues) {
  const rows = issues
    .map((issue) => {
      const filename = issueFilename(issue.number);
      const labels =
        issue.labels.length === 0
          ? "—"
          : issue.labels.map((label) => `\`${markdownCell(label.name)}\``).join(", ");

      return `| [${String(issue.number).padStart(4, "0")} — ${markdownCell(issue.title)}](${filename}) | ${issue.state.toLowerCase()} | ${labels} | ${issue.updatedAt.slice(0, 10)} |`;
    })
    .join("\n");

  return `# Issues

> Generated from [${repository}](https://github.com/${repository}/issues). GitHub is canonical. Edit issues there, then run \`pnpm issues:pull\`.

| Issue | State | Labels | Updated |
| --- | --- | --- | --- |
${rows}
`;
}

const repository =
  readArgument("--repo") ??
  runGh(["repo", "view", "--json", "nameWithOwner", "--jq", ".nameWithOwner"]);

const issues = JSON.parse(
  runGh([
    "issue",
    "list",
    "--repo",
    repository,
    "--state",
    "all",
    "--limit",
    "10000",
    "--json",
    fields,
  ]),
).sort((left, right) => left.number - right.number);

mkdirSync(issuesDirectory, { recursive: true });

const expectedFiles = new Set(issues.map((issue) => issueFilename(issue.number)));
for (const filename of readdirSync(issuesDirectory)) {
  if (/^iss-\d{4,}\.md$/.test(filename) && !expectedFiles.has(filename)) {
    unlinkSync(join(issuesDirectory, filename));
  }
}

for (const issue of issues) {
  writeAtomically(
    join(issuesDirectory, issueFilename(issue.number)),
    renderIssue(issue),
  );
}
writeAtomically(
  join(issuesDirectory, "index.md"),
  renderIndex(repository, issues),
);

console.log(`Synced ${issues.length} issues from ${repository} to .issues/.`);
